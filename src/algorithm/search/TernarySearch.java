package algorithm.search;

/**
 * 三分查找 — 经典模板题
 * <p>
 * 【模板题】两数之和为 S，求最大乘积
 * <p>
 * 给定正整数 S，找两个正整数 x、y，满足 x + y = S，使得 x * y 最大。
 * 其中 x 的取值范围是 [1, S - 1]（y = S - x 也必须是正整数）。
 *
 * @Description: 三分查找
 * @Date: 2026/7/30
 */
public class TernarySearch {

    /**
     * ═══════════════════════════════════════════════════════════════════
     *  一、为什么这道题是三分查找的经典模板？
     * ═══════════════════════════════════════════════════════════════════
     * <p>
     * 把 x 看作变量，乘积可以写成关于 x 的函数：
     * <pre>
     *   f(x) = x * (S - x) = -x² + S·x
     * </pre>
     * 这是一个开口向下的抛物线，在 x = S/2 处取最大值。
     * <p>
     * 图像上先增后减，就是「单峰函数」：
     * <pre>
     *         ⭐  ← 峰值在 x = S/2
     *        / \
     *       /   \
     *      /     \
     *   x=1       x=S-1
     * </pre>
     * 三分查找专门解决这类问题：函数在某个区间上先单调增、再单调减（或反过来）。
     */

    /**
     * ═══════════════════════════════════════════════════════════════════
     *  二、为什么要「除以 3」？和二分查找有什么区别？
     * ═══════════════════════════════════════════════════════════════════
     * <p>
     * 【二分查找】区间切成 <strong>2</strong> 段，只需 <strong>1</strong> 个中点：
     * <pre>
     *   l ────── mid ────── r        比较 arr[mid] 与 target，丢掉一半
     *   mid = l + (r - l) / 2        ← 除以 2
     * </pre>
     * 前提：数组<strong>单调</strong>（有序）。mid 左边全小、右边全大（或反过来），
     * 一次比较就能确定答案在哪一半。
     * <p>
     * 【三分查找】区间切成 <strong>3</strong> 段，需要 <strong>2</strong> 个采样点：
     * <pre>
     *   l ── m1 ── m2 ── r           比较 f(m1) 与 f(m2)，丢掉三分之一
     *   m1 = l + (r - l) / 3         ← 从左往右 1/3 处
     *   m2 = r - (r - l) / 3         ← 从右往左 1/3 处（= 从左往右 2/3 处）
     * </pre>
     * 前提：函数<strong>单峰</strong>（先增后减）。只有 1 个中点不够判断峰值在哪边——
     * 单峰函数上 f(mid) 可能在上升段，也可能在下降段，单凭一个点无法决定往哪搜。
     * 取 m1、m2 两个点，比较它们的大小关系，就能确定峰值在左 1/3、中 1/3 还是右 1/3，
     * 然后安全地丢掉一整段。
     * <p>
     * 【为什么 f(m1) &lt; f(m2) 就能丢掉 [l, m1]？】
     * <pre>
     *   单峰函数在 m1 左侧全部 ≤ f(m1)（还在上升或已过峰值但在 m1 左边）
     *   而 f(m1) &lt; f(m2)，说明峰值不可能在 m1 左边（那边最大值不超过 f(m1)）
     *   → 安全舍弃 [l, m1]，令 l = m1 + 1
     *
     *   反之 f(m1) ≥ f(m2)，峰值不可能在 m2 右边
     *   → 安全舍弃 [m2, r]，令 r = m2 - 1
     * </pre>
     * <p>
     * 【对比总结】
     * <pre>
     *   ┌──────────┬─────────────────┬─────────────────┐
     *   │          │ 二分查找         │ 三分查找         │
     *   ├──────────┼─────────────────┼─────────────────┤
     *   │ 适用场景  │ 单调（有序数组）  │ 单峰/单谷函数    │
     *   │ 切分方式  │ 1 刀 → 2 段     │ 2 刀 → 3 段     │
     *   │ 采样点数  │ 1 个 mid        │ 2 个 m1, m2     │
     *   │ 每轮丢弃  │ 一半            │ 三分之一         │
     *   │ 除以几    │ 2               │ 3               │
     *   └──────────┴─────────────────┴─────────────────┘
     * </pre>
     */

    /**
     * ═══════════════════════════════════════════════════════════════════
     *  三、三分查找核心思路
     * ═══════════════════════════════════════════════════════════════════
     * <p>
     * 每次把区间 [l, r] 分成三等份，取两个点 m1、m2：
     * <pre>
     *   l ─── m1 ─── m2 ─── r
     * </pre>
     * 比较 f(m1) 和 f(m2)：
     * <ul>
     *   <li>f(m1) &lt; f(m2)：峰值在 m1 右侧，舍弃 [l, m1]，令 l = m1 + 1</li>
     *   <li>f(m1) ≥ f(m2)：峰值在 m2 左侧，舍弃 [m2, r]，令 r = m2 - 1</li>
     * </ul>
     * 重复直到 l == r，即为最优 x。
     * <p>
     * 时间复杂度 O(log n)，n 为区间长度。
     */

    /**
     * ═══════════════════════════════════════════════════════════════════
     *  四、样例推演（S = 20）
     * ═══════════════════════════════════════════════════════════════════
     * <pre>
     *   f(x) = x * (20 - x)
     *
     *   第1轮：l=1, r=19
     *         m1=7  → f(7)  = 7×13 = 91
     *         m2=13 → f(13) = 13×7 = 91
     *         91 ≥ 91 → r = 12
     *
     *   第2轮：l=1, r=12
     *         m1=4  → f(4)  = 64
     *         m2=9  → f(9)  = 99
     *         64 &lt; 99 → l = 5
     *
     *   第3轮：l=5, r=12
     *         m1=7  → f(7)  = 91
     *         m2=10 → f(10) = 100  ← 最大值
     *         91 &lt; 100 → l = 8
     *
     *   第4轮：l=8, r=12
     *         m1=9  → f(9)  = 99
     *         m2=11 → f(11) = 99
     *         99 ≥ 99 → r = 10
     *
     *   第5轮：l=8, r=10
     *         m1=8  → f(8)  = 96
     *         m2=9  → f(9)  = 99
     *         96 &lt; 99 → l = 9
     *
     *   第6轮：l=9, r=10
     *         m1=9, m2=9 → l=10, r=9 → 结束
     *
     *   答案：x = 10，y = 10，最大乘积 = 100
     *   （理论值：S/2 = 10，完全吻合）
     * </pre>
     */

    /** 计算乘积 f(x) = x * (S - x) */
    private static long product(int x, int S) {
        return (long) x * (S - x);
    }

    /**
     * ═══════════════════════════════════════════════════════════════════
     *  五、三分查找模板代码
     * ═══════════════════════════════════════════════════════════════════
     * <p>
     * 以后遇到任何「单峰函数求最大值」的题，只需把 product(x, S) 换成你的 f(x) 即可。
     */
    public static int maxProduct(int S) {
        int l = 1, r = S - 1;
        while (l < r) {
            // 把 [l, r] 均分成 3 段，取左 1/3 处和右 1/3 处两个采样点
            // 为什么除以 3？因为要有 2 个点才能把区间切成 3 段，每次丢掉 1/3
            // 对比二分：mid = l + (r-l)/2 只有 1 个点，切成 2 段，每次丢掉 1/2
            int m1 = l + (r - l) / 3;  // 左采样点：距左端 1/3 长度处
            int m2 = r - (r - l) / 3;  // 右采样点：距右端 1/3 长度处（= 距左端 2/3 处）

            if (product(m1, S) < product(m2, S)) {
                // f(m1) < f(m2)：峰值不可能在 m1 左侧（那边最大值 ≤ f(m1)）
                // 舍弃左 1/3 段 [l, m1]，缩到 [m1+1, r]
                l = m1 + 1;
            } else {
                // f(m1) ≥ f(m2)：峰值不可能在 m2 右侧（那边最大值 ≤ f(m2) ≤ f(m1)）
                // 舍弃右 1/3 段 [m2, r]，缩到 [l, m2-1]
                r = m2 - 1;
            }
        }
        return (int) product(l, S);
    }

    /** 返回最优的 x（y = S - x） */
    public static int maxProductX(int S) {
        int l = 1, r = S - 1;
        while (l < r) {
            int m1 = l + (r - l) / 3;
            int m2 = r - (r - l) / 3;
            if (product(m1, S) < product(m2, S)) {
                l = m1 + 1;  // 丢左 1/3
            } else {
                r = m2 - 1;  // 丢右 1/3
            }
        }
        return l;
    }

    /**
     * ═══════════════════════════════════════════════════════════════════
     *  六、与暴力、数学解法的对比
     * ═══════════════════════════════════════════════════════════════════
     * <pre>
     *   暴力枚举：for x in [1, S-1] 取 max → O(S)，S 很大会超时
     *   数学公式：x = S/2 时最大     → O(1)，但这题太简单，竞赛题 f(x) 往往没有公式
     *   三分查找：O(log S)           → 通用模板，换 f(x) 就能用
     * </pre>
     */
    public static int maxProductBruteForce(int S) {
        int best = 0;
        for (int x = 1; x <= S - 1; x++) {
            best = Math.max(best, (int) product(x, S));
        }
        return best;
    }

    public static void main(String[] args) {
        int S = 20;

        int x = maxProductX(S);
        int maxProd = maxProduct(S);
        int brute = maxProductBruteForce(S);

        System.out.println("=== 经典模板题：两数之和为 S，求最大乘积 ===");
        System.out.println("S = " + S);
        System.out.println("最优解：x = " + x + "，y = " + (S - x) + "，最大乘积 = " + maxProd);
        System.out.println("暴力验证 = " + brute + "（应与三分结果一致）");
        System.out.println("数学公式 S/2 = " + (S / 2) + "，乘积 = " + product(S / 2, S));
        System.out.println();
        System.out.println("【三分模板】求最大值：");
        System.out.println("  while (l < r) {");
        System.out.println("      m1 = l + (r - l) / 3;");
        System.out.println("      m2 = r - (r - l) / 3;");
        System.out.println("      if (f(m1) < f(m2)) l = m1 + 1;");
        System.out.println("      else               r = m2 - 1;");
        System.out.println("  }");
        System.out.println("【求最小值】只需把 f(m1) < f(m2) 改成 f(m1) > f(m2)");
    }
}
